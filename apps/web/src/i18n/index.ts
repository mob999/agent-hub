export function isSupportedLocale(value: string | null | undefined): value is SupportedLocale {
  return supportedLocales.includes(value as SupportedLocale)
}

function normalizeLocale(value: string | null | undefined): SupportedLocale | null {
  if (!value) {
    return null
  }

  const normalized = value.toLowerCase()
  if (normalized === 'zh' || normalized.startsWith('zh-')) {
    return 'zh-CN'
  }

  if (normalized === 'en' || normalized.startsWith('en-')) {
    return 'en'
  }

  return null
}

export function getInitialLocale(input?: {
  storedLocale?: string | null
  navigatorLanguage?: string | null
  navigatorLanguages?: readonly string[]
}): SupportedLocale {
  const storedLocale =
    input?.storedLocale ??
    (typeof window === 'undefined'
      ? null
      : window.localStorage.getItem(localeStorageKey))
  if (isSupportedLocale(storedLocale)) {
    return storedLocale
  }

  const languages =
    input?.navigatorLanguages ??
    (typeof navigator === 'undefined'
      ? []
      : navigator.languages)
  const language =
    normalizeLocale(input?.navigatorLanguage) ??
    languages.map(normalizeLocale).find((locale): locale is SupportedLocale => locale !== null)

  return language ?? 'en'
}

export async function changeLocale(locale: SupportedLocale): Promise<void> {
  if (!isSupportedLocale(locale)) {
    return
  }

  if (typeof window !== 'undefined') {
    window.localStorage.setItem(localeStorageKey, locale)
  }
  await i18n.changeLanguage(locale)
}

void i18n
  .use(initReactI18next)
  .init({
    fallbackLng: 'en',
    interpolation: {
      escapeValue: false,
    },
    lng: getInitialLocale(),
    resources,
    supportedLngs: supportedLocales,
  })

